"""Optional image-region advice for the generated wood-frame browser scene."""

import asyncio
import json
import re
from tempfile import TemporaryDirectory

import cv2

from carton_hydrogen import ACP, AGY, EFFORT, MODEL, image_block, valid_box


PROMPT = """This is a generated image of a timber assembly demonstration.
Identify the long loose horizontal timber on the dark table. The two shorter
light-colored faces belong to separate upright posts. Indicate whether enough
of the long timber is visible to search for its complete top-face outline.
If a dark foreground part covers it, report occluded instead of drawing a
complete outline from memory. Coordinates are normalized integers 0..1000
in [top,left,bottom,right] order. Reply only with JSON keys status, box_2d,
and reason. Status is found, occluded, absent, or uncertain. For found give a
box covering the entire visible long timber. For occluded the box is optional.
For absent or uncertain set box_2d to null. Keep reason to one sentence.
Use the given image only. Do not use tools or infer metric coordinates."""


def _parse_answer(text):
    fenced = re.fullmatch(r"```(?:json)?\s*(\{.*\})\s*```", text.strip(), re.DOTALL | re.IGNORECASE)
    answer = json.loads(fenced[1] if fenced else text)
    if not isinstance(answer, dict) or set(answer) != {"status", "box_2d", "reason"}:
        raise ValueError("Unexpected Hydrogen advice format.")
    status = answer["status"]
    box = answer["box_2d"]
    valid_region = ((status == "found" and valid_box(box))
                    or (status == "occluded" and (box is None or valid_box(box)))
                    or (status in ("absent", "uncertain") and box is None))
    if not valid_region or not isinstance(answer["reason"], str) or not 0 < len(answer["reason"].strip()) <= 300:
        raise ValueError("Invalid Hydrogen visibility status, image region, or reason.")
    return answer


async def _request(jpeg):
    with TemporaryDirectory(prefix="uwa-wood-frame-hydrogen-") as isolated:
        process = await asyncio.create_subprocess_exec(
            str(AGY), "acp", "--include-default-customizations=false", "--disable-telemetry",
            cwd=isolated, stdin=asyncio.subprocess.PIPE, stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.DEVNULL,
        )
        client = ACP(process)
        try:
            async with asyncio.timeout(12):
                capabilities = await client.request("initialize", {"protocolVersion": 1, "clientCapabilities": {},
                    "clientInfo": {"name": "uwa-wood-frame-browser", "version": "1"}})
                if not capabilities["agentCapabilities"]["promptCapabilities"].get("image"):
                    raise RuntimeError("Antigravity did not advertise image input.")
                session = await client.request("session/new", {"cwd": isolated, "mcpServers": []})
                client.session_id = session["sessionId"]
                params = {"sessionId": client.session_id}
                await client.request("session/set_config_option", {**params, "configId": "model", "value": MODEL})
                config = await client.request("session/set_config_option",
                                              {**params, "configId": "thought_level", "value": EFFORT})
                selected = {item["id"]: item["currentValue"] for item in config["configOptions"]}
                if selected.get("model") != MODEL or selected.get("thought_level") != EFFORT:
                    raise RuntimeError("Antigravity did not select Hydrogen Low.")
            async with asyncio.timeout(20):
                result = await client.request("session/prompt", {**params, "prompt": [
                    {"type": "text", "text": PROMPT}, image_block(jpeg)]})
            if result.get("stopReason") != "end_turn" or client.used_tools:
                raise RuntimeError("Hydrogen did not complete image-only advice.")
            answer = _parse_answer("".join(client.text))
            return {**answer, "model": MODEL, "effort": EFFORT, "source": "synthetic_rgb_browser"}
        finally:
            process.stdin.close()
            try:
                await asyncio.wait_for(process.communicate(), 1)
            except TimeoutError:
                if process.returncode is None:
                    process.kill()
                await process.communicate()


def suggest_synthetic_beam(image):
    """Request one image-only hint for RGB generated by the browser observation module."""
    encoded, jpeg = cv2.imencode(".jpg", image, [cv2.IMWRITE_JPEG_QUALITY, 86])
    if not encoded:
        raise ValueError("Could not encode the synthetic observation.")
    try:
        return asyncio.run(_request(jpeg.tobytes()))
    except TimeoutError as error:
        raise RuntimeError("Hydrogen image advice timed out.") from error
    except (KeyError, TypeError) as error:
        raise RuntimeError("Antigravity returned an incompatible ACP response.") from error
